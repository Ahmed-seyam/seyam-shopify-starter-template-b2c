/**
 * Pulls the store's published languages and markets (countries) from the
 * Storefront API and writes src/i18n/locales.generated.ts, which routing
 * and the header switchers consume:
 *
 *   npm run sync-locales
 *
 * Re-run whenever markets/languages change in Shopify admin
 * (Settings → Markets / Settings → Languages). The store's default
 * language and country are placed first — they form the default locale.
 */

const domain = process.env.SHOPIFY_STORE_DOMAIN?.replace(/^https?:\/\//, "")
  .replace(/\/.*$/, "");
const token = process.env.SHOPIFY_STOREFRONT_TOKEN;
const apiVersion = process.env.SHOPIFY_API_VERSION ?? "2025-07";

if (!domain || !token) {
  console.error("Set SHOPIFY_STORE_DOMAIN and SHOPIFY_STOREFRONT_TOKEN in .env");
  process.exit(1);
}

const QUERY = /* GraphQL */ `
  query localization {
    localization {
      language {
        isoCode
      }
      country {
        isoCode
      }
      availableLanguages {
        isoCode
        endonymName
      }
      availableCountries {
        isoCode
        name
        currency {
          isoCode
        }
      }
    }
  }
`;

const response = await fetch(`https://${domain}/api/${apiVersion}/graphql.json`, {
  method: "POST",
  headers: {
    "Content-Type": "application/json",
    "X-Shopify-Storefront-Access-Token": token,
  },
  body: JSON.stringify({ query: QUERY }),
});

const body = await response.json();
if (!response.ok || body.errors?.length) {
  console.error(JSON.stringify(body.errors ?? body, null, 2));
  process.exit(1);
}

const { language, country, availableLanguages, availableCountries } =
  body.data.localization;

// Default language/country first — routing derives defaultLocale from them.
const sortFirst = (items, isoCode) => [
  ...items.filter((item) => item.isoCode === isoCode),
  ...items.filter((item) => item.isoCode !== isoCode),
];

const languages = sortFirst(availableLanguages, language.isoCode).map(
  (item) => ({
    code: item.isoCode.toLowerCase(),
    label: item.endonymName,
  }),
);

const countries = sortFirst(availableCountries, country.isoCode).map(
  (item) => ({
    code: item.isoCode.toLowerCase(),
    label: `${item.name} (${item.currency.isoCode})`,
  }),
);

const file = `// AUTO-GENERATED by scripts/sync-locales.mjs — do not edit by hand.
// Source of truth: Shopify admin → Settings → Markets / Languages.
// Re-sync with: npm run sync-locales

export const languages = ${JSON.stringify(languages, null, 2)} as const;

export const countries = ${JSON.stringify(countries, null, 2)} as const;
`;

const { writeFileSync } = await import("node:fs");
writeFileSync(new URL("../src/i18n/locales.generated.ts", import.meta.url), file);

console.log(
  `✓ src/i18n/locales.generated.ts — ${languages.length} language(s): ` +
    `${languages.map((l) => l.code).join(", ")}; ${countries.length} ` +
    `market(s): ${countries.map((c) => c.code).join(", ")}`,
);
console.log(
  "  Reminder: each language needs a messages/<code>.json (falls back to en).",
);
